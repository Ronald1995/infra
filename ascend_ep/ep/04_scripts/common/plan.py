"""Benchmark plan: one configuration that expands the whole EP test matrix.

A plan composes four layers, from lowest to highest priority::

    Global base configuration
    EP size configuration        (environment only: EP/TP size, model, topology)
    Suite configuration          (scenario only: workload, benchmark dimensions)
    Case parameter variant       (generated by ``common.variants``)

The result is one task list covering ``EP Size x Suite x Case x Operator x
Parameter Variant``.  Nothing about the case scope is duplicated in the EP size
files: they only describe the environment, so EP8, EP64 and EP128 are guaranteed
to run the same catalog.
"""
from collections import Counter
from copy import deepcopy
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from common import config_audit
from common.cases import alias_map, case_counts, catalog
from common.config import (LEVELS, load_raw, load_suite_overlays, merge, provenance_record,
                           resolve_config, validate)
from common.registry import ROOT
from common.scheduler import (ALIAS_MODES, case_index, check_completeness, make_plan,
                              merge_tasks)
from common.storage import fingerprint
from common.suites import apply_scaling, normalize, select, workload_policy
from common.variants import case_dimension_records

PLAN_SCHEMA_VERSION = 1
#: ``catalog``     every canonical case once, under the base configuration.  This
#:                 is the historical behaviour and stays the default for old
#:                 plan files that do not declare a mode.
#: ``full_matrix`` the complete catalog **plus** every listed specialised suite,
#:                 each expanded with its own scenario configuration.  Identical
#:                 tasks are de-duplicated, different parameters are not.
PLAN_MODES = ("catalog", "full_matrix")
DEFAULT_MODE = "catalog"
DEFAULT_EXECUTION = {
    "fail_fast": False,
    "continue_on_unsupported": True,
    "continue_on_error": True,
    "run_ep_sizes_sequentially": True,
    # Full Matrix turns this on: every planned task must reach a terminal status
    # before the run may be reported as complete.  `not_run` is never a pass.
    "require_complete_execution": False,
}
DEFAULT_REPORT = {
    "compare_ep_sizes": True,
    "compare_operators": True,
    "generate_coverage_matrix": True,
}


def _relative(path):
    try:
        return Path(path).resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return str(Path(path).resolve())


@dataclass(frozen=True)
class PlanPoint:
    """One (EP size, suite, configuration layer) expansion point."""

    ep_size: int
    suite: str
    config: dict
    sources: tuple[str, ...]
    notes: tuple[str, ...] = ()
    #: ``dotted field -> {value, source}`` for every leaf of the effective
    #: configuration.  The plan writes it next to the manifest, so "why did this
    #: task have cores=[2]?" is answerable without re-reading every YAML file.
    provenance: dict = field(default_factory=dict)

    @property
    def fingerprint(self):
        effective = {key: value for key, value in self.config.items() if key != "suite_id"}
        return fingerprint(effective)

    @property
    def provenance_fingerprint(self):
        return fingerprint(self.provenance)


@dataclass
class BenchmarkPlan:
    path: Path
    name: str
    ep_sizes: list
    operators: object
    levels: list
    suites: list
    aliases: str = "dedupe"
    mode: str = DEFAULT_MODE
    base_config: Path | None = None
    ep_configs: dict = field(default_factory=dict)
    suite_configs: dict = field(default_factory=dict)
    execution: dict = field(default_factory=dict)
    report: dict = field(default_factory=dict)
    cases: list = field(default_factory=list)
    topology: dict = field(default_factory=dict)

    @property
    def directory(self):
        return self.path.parent

    def ep_config(self, ep_size):
        explicit = self.ep_configs.get(ep_size) or self.ep_configs.get(str(ep_size))
        if explicit:
            return explicit
        candidate = self.directory / f"ep{ep_size}_bf16.yaml"
        if candidate.is_file():
            return candidate
        raise ValueError(
            f"benchmark plan has no EP{ep_size} configuration; add ep_configs.{ep_size} "
            f"or provide {candidate.name} next to the plan")

    def metadata(self):
        return {
            "schema_version": PLAN_SCHEMA_VERSION,
            "name": self.name,
            "mode": self.mode,
            "path": _relative(self.path),
            "ep_sizes": list(self.ep_sizes),
            "levels": list(self.levels),
            "suites": list(self.suites),
            "operators": self.operators,
            "aliases": self.aliases,
            "execution": dict(self.execution),
            "report": dict(self.report),
            "topology_pattern": dict(self.topology),
            "config_sources": {
                "base": _relative(self.base_config) if self.base_config else None,
                "ep": {str(size): _relative(self.ep_config(size)) for size in self.ep_sizes},
                "suites": {suite_id: _relative(path)
                           for suite_id, path in sorted(self.suite_configs.items())},
            },
        }


def _as_bool(mapping, key, default):
    value = mapping.get(key, default)
    if not isinstance(value, bool):
        raise ValueError(f"plan execution flag {key} must be a boolean")
    return value


def _resolve(directory, value):
    if value is None:
        return None
    path = Path(str(value))
    return path if path.is_absolute() else (directory / path)


def load_plan(path):
    """Read and validate one benchmark plan."""
    path = Path(path).resolve()
    raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        raise ValueError("benchmark plan must be a YAML mapping")
    spec = raw.get("plan")
    if spec is None and isinstance(raw.get("matrix"), dict):
        # The documented shorthand: matrix: {ep_sizes, operators, levels, suites}
        spec = raw["matrix"]
    if not isinstance(spec, dict):
        raise ValueError("benchmark plan must define a 'plan' mapping (or a 'matrix' mapping)")
    if spec.get("schema_version", raw.get("schema_version", PLAN_SCHEMA_VERSION)) != PLAN_SCHEMA_VERSION:
        raise ValueError("unsupported benchmark plan schema version")

    ep_sizes = spec.get("ep_sizes") or raw.get("ep_sizes")
    if not isinstance(ep_sizes, list) or not ep_sizes:
        raise ValueError("benchmark plan must declare a non-empty ep_sizes list")
    if any(type(size) is not int or size < 1 for size in ep_sizes):
        raise ValueError("plan ep_sizes must be positive integers")
    if len(set(ep_sizes)) != len(ep_sizes):
        raise ValueError("plan ep_sizes must be unique")

    levels = spec.get("levels") or list(LEVELS)
    if not isinstance(levels, list) or not levels or set(levels) - set(LEVELS):
        raise ValueError(f"plan levels must be a subset of {LEVELS}")

    suites = spec.get("suites") or ["all"]
    if isinstance(suites, str):
        suites = [suites]
    if not isinstance(suites, list) or not suites:
        raise ValueError("plan suites must be a non-empty list")
    suites = list(dict.fromkeys(normalize(item) for item in suites))

    mode = spec.get("mode", DEFAULT_MODE)
    if mode not in PLAN_MODES:
        raise ValueError(f"plan mode must be one of {PLAN_MODES}")
    if mode == "full_matrix" and "all" not in suites:
        raise ValueError(
            "a full_matrix plan must list the `all` suite: `all` expands the complete case "
            "catalog and every other suite adds its specialised scenario configuration")

    operators = spec.get("operators", "all")
    if operators != "all" and not isinstance(operators, list):
        raise ValueError("plan operators must be 'all' or a list of operator IDs")

    aliases = spec.get("aliases", "dedupe")
    if aliases not in ALIAS_MODES:
        raise ValueError(f"plan aliases must be one of {ALIAS_MODES}")

    base = _resolve(path.parent, spec.get("base_config") or raw.get("base_config"))
    ep_configs = {
        int(size): _resolve(path.parent, item)
        for size, item in (spec.get("ep_configs") or raw.get("ep_configs") or {}).items()
    }
    suite_configs = {
        normalize(suite_id): _resolve(path.parent, item)
        for suite_id, item in (spec.get("suite_configs") or raw.get("suite_configs") or {}).items()
    }
    execution = {**DEFAULT_EXECUTION, **(raw.get("execution") or {})}
    report = {**DEFAULT_REPORT, **(raw.get("report") or {})}
    for key in DEFAULT_EXECUTION:
        _as_bool(execution, key, DEFAULT_EXECUTION[key])
    for key in DEFAULT_REPORT:
        _as_bool(report, key, DEFAULT_REPORT[key])
    if not execution["run_ep_sizes_sequentially"]:
        raise ValueError(
            "run_ep_sizes_sequentially must be true: one EP group is active at a time so "
            "benchmarks never contend for the same devices")
    cases = spec.get("cases") or raw.get("cases") or []
    if not isinstance(cases, list):
        raise ValueError("plan cases must be a list of case IDs")

    topology = spec.get("topology") or raw.get("topology") or {}
    if not isinstance(topology, dict):
        raise ValueError("plan topology must be a mapping")
    for key in ("server_size", "supernode_size"):
        if key in topology and (type(topology[key]) is not int or topology[key] < 1):
            raise ValueError(f"plan topology.{key} must be a positive integer")
    for key in ("rank_to_server", "server_to_supernode"):
        if key in topology and not isinstance(topology[key], (list, dict)):
            raise ValueError(f"plan topology.{key} must be a list or a mapping")
    if "verified" in topology and not isinstance(topology["verified"], bool):
        raise ValueError("plan topology.verified must be a boolean")

    return BenchmarkPlan(
        path=path, name=str(spec.get("name") or path.stem), ep_sizes=list(ep_sizes),
        operators=operators, levels=list(levels), suites=suites, aliases=aliases,
        mode=mode, base_config=base, ep_configs=ep_configs, suite_configs=suite_configs,
        execution=execution, report=report, cases=list(cases), topology=topology)


def _rank_domains(value, size, name):
    """Normalise one rank->domain declaration to a list with one entry per rank.

    Accepts ``[domain per rank]``, ``{rank: domain}`` and ``{domain: [ranks]}`` so
    a deployment can paste whichever form it already has.  A map that does not
    cover every rank exactly once is rejected instead of being padded.
    """
    if isinstance(value, dict):
        if all(isinstance(item, (list, tuple)) for item in value.values()):
            mapping = {}
            for domain, ranks in value.items():
                for rank in ranks:
                    mapping[int(rank)] = domain
        else:
            mapping = {int(rank): domain for rank, domain in value.items()}
        if sorted(mapping) != list(range(size)):
            raise ValueError(f"topology {name} must map every one of the {size} ranks")
        return [mapping[rank] for rank in range(size)]
    if isinstance(value, (list, tuple)):
        if len(value) != size:
            raise ValueError(f"topology {name} must contain one domain per rank ({size})")
        return list(value)
    raise ValueError(f"topology {name} must be a list or a mapping")


def _apply_topology(plan, config, ep_size):
    """Compose the rank-to-server and server-to-supernode map for one EP point.

    Resolution order, highest first:

    1. the EP environment configuration (``topology.server_ids``) -- the
       deployment's own map, which the plan must never overwrite;
    2. an explicit plan map (``topology.rank_to_server`` / ``server_to_supernode``);
    3. the plan *pattern* (``server_size`` / ``supernode_size``), derived.

    The last one is a synthetic layout, so it is recorded with
    ``source: plan`` and ``verified: false``.  Reporting never claims a derived
    map is physically verified; a real map sets ``verified: true`` itself.
    """
    pattern = dict(plan.topology or {})
    topology = dict(config.get("topology") or {})
    source = topology.get("source")
    verified = bool(topology.get("verified", False))
    server_ids = topology.get("server_ids")
    supernode_ids = topology.get("supernode_ids")

    if server_ids is not None:
        server_ids = _rank_domains(server_ids, ep_size, "server_ids")
        source = source or "environment"
    elif pattern.get("rank_to_server") is not None:
        server_ids = _rank_domains(pattern["rank_to_server"], ep_size, "rank_to_server")
        source = "explicit"
        verified = verified or bool(pattern.get("verified", False))
    elif pattern.get("server_size"):
        server_size = pattern["server_size"]
        server_ids = [rank // server_size for rank in range(ep_size)]
        source = "plan"
        verified = False

    if supernode_ids is not None:
        supernode_ids = _rank_domains(supernode_ids, ep_size, "supernode_ids")
    elif pattern.get("server_to_supernode") and server_ids is not None:
        mapping = pattern["server_to_supernode"]
        missing = sorted({domain for domain in server_ids
                          if domain not in mapping and str(domain) not in mapping})
        if missing:
            raise ValueError(
                f"topology server_to_supernode does not cover server(s) {', '.join(map(str, missing))}")
        supernode_ids = [mapping.get(domain, mapping.get(str(domain))) for domain in server_ids]
    elif pattern.get("supernode_size"):
        supernode_size = pattern["supernode_size"]
        supernode_ids = [rank // supernode_size for rank in range(ep_size)]

    if server_ids is None and supernode_ids is None:
        # Nothing was declared: keep the topology empty and make the absence
        # explicit so a cross-server comparison cannot silently run.
        return {**config, "topology": {**topology, "source": "unavailable", "verified": False}}
    composed = {**topology, "source": source or "unavailable", "verified": verified}
    if server_ids is not None:
        composed["server_ids"] = server_ids
        composed["server_size"] = max(Counter(server_ids).values())
    if supernode_ids is not None:
        composed["supernode_ids"] = supernode_ids
    return {**config, "topology": composed}


def _adapt_router_bias(config):
    """Return a note when a routing bias cannot be expressed at this EP size."""
    workload = dict(config["workload"])
    if workload.get("router_bias") == "remote_rank":
        domains = set(config["topology"].get("server_ids") or ())
        if len(domains) < 2:
            workload["router_bias"] = None
            return ({**config, "workload": workload},
                    "router_bias=remote_rank needs two server domains; this EP group is one domain")
    return config, None


def plan_points(plan, ep_sizes=None, suites=None, levels=None):
    """Expand a plan into configuration points (no capability checks yet).

    Every layer is read *raw* and composed by :func:`common.config.resolve_config`,
    which also returns the field provenance.  Defaults are therefore applied once,
    after the whole stack is composed: an EP environment that omits a field can no
    longer inject its implicit default over an explicit base value.
    """
    ep_sizes = list(ep_sizes or plan.ep_sizes)
    suites = list(suites or plan.suites)
    if isinstance(suites, str):
        suites = [suites]
    suites = [normalize(item) for item in suites]
    base_layer = None
    if plan.base_config:
        base_raw, base_provenance = load_raw(plan.base_config)
        base_layer = ("base_config", base_raw, base_provenance)
    points = []
    for ep_size in ep_sizes:
        environment_raw, environment_provenance = load_raw(plan.ep_config(ep_size))
        for suite_id in suites:
            overlay_path = plan.suite_configs.get(suite_id)
            overlays = (load_suite_overlays(overlay_path, ep_size) if overlay_path
                        else [({}, {})])
            for overlay, overlay_provenance in overlays:
                layers = [layer for layer in (base_layer,) if layer is not None]
                layers.append(("environment", environment_raw, environment_provenance))
                layers.append(("suite", overlay, overlay_provenance))
                config, provenance = resolve_config(layers)
                config["suite_id"] = suite_id
                config = _apply_topology(plan, config, ep_size)
                provenance.update({f"topology.{key}": _topology_source(config, plan)
                                   for key in (config.get("topology") or {})})
                config, note = _adapt_router_bias(config)
                config = apply_scaling(suite_id, config, ep_size)
                if workload_policy(suite_id):
                    provenance["workload.tokens_per_rank"] = (
                        f"suite:{suite_id} scaling ({workload_policy(suite_id)})")
                    provenance["model.num_experts"] = (
                        f"suite:{suite_id} scaling ({workload_policy(suite_id)})")
                # The plan decides the level scope; an environment or suite file
                # must not narrow it back to one EP size or one level.
                if levels:
                    config["benchmark"]["levels"] = list(levels)
                    provenance["benchmark.levels"] = "plan"
                validate(config)
                sources = [plan.path]
                if plan.base_config:
                    sources.append(plan.base_config)
                sources.append(plan.ep_config(ep_size))
                if overlay_path:
                    sources.append(overlay_path)
                points.append(PlanPoint(
                    ep_size, suite_id, config,
                    tuple(dict.fromkeys(str(item) for item in sources)),
                    (note,) if note else (),
                    provenance_record(config, provenance)))
    return points


def _topology_source(config, plan):
    """Name where one EP point's topology came from."""
    topology = config.get("topology") or {}
    source = topology.get("source") or "unavailable"
    if source == "environment":
        return "environment"
    if source == "explicit":
        return "plan (explicit rank map)"
    if source == "plan":
        return "plan pattern (synthetic, unverified)"
    return source


def expected_cases(plan, suites=None, levels=None, cases=None):
    """The cases a plan run must produce a task for.

    ``--cases`` is an explicit user narrowing, so it defines the expected set
    directly instead of being intersected with the suite/level selection.
    """
    if cases or plan.cases:
        wanted = list(dict.fromkeys([*plan.cases, *(cases or [])]))
        return {case_id for case_id in wanted if case_id in catalog()}
    suites = [normalize(item) for item in (suites or plan.suites)]
    return set(select(suites, levels or plan.levels))


@dataclass
class PlanRun:
    """The expanded matrix plus the evidence that it is complete."""

    plan: BenchmarkPlan
    points: list
    tasks: list
    expected: set
    coverage: dict

    def metadata(self):
        data = self.plan.metadata()
        selected_eps = sorted({point.ep_size for point in self.points})
        selected_suites = list(dict.fromkeys(point.suite for point in self.points))
        suite_tasks = {}
        for task in self.tasks:
            for label in task.get("plan_points") or (task.get("plan_point"),):
                suite_tasks[label] = suite_tasks.get(label, 0) + 1
        data.update({
            "declared_ep_sizes": list(self.plan.ep_sizes),
            "declared_suites": list(self.plan.suites),
            "ep_sizes": selected_eps,
            "suites": selected_suites,
            "topology": {str(ep): _topology_summary(self.points, ep) for ep in selected_eps},
            "config_points": [
                {"ep_size": point.ep_size, "suite": point.suite,
                 "sources": [_relative(item) for item in point.sources],
                 "notes": list(point.notes),
                 "topology": _topology_record(point.config),
                 "task_count": suite_tasks.get(f"EP{point.ep_size}/{point.suite}", 0),
                 "fingerprint": point.fingerprint,
                 "provenance_id": point.provenance_fingerprint,
                 "dimensions": case_dimension_records(
                     [case for case in catalog().values() if case.level == "L0"],
                     point.config["benchmark"], point.ep_size),
                 "config_provenance": point.provenance}
                for point in self.points
            ],
            "catalog": {
                case_id: {"level": case.level, "category": case.category,
                          "alias_of": case.alias_of, "canonical": case.alias_of is None}
                for case_id, case in sorted(catalog().items())
            },
            "case_aliases": alias_map(),
            "case_counts": case_counts(),
            "expected_cases": sorted(self.expected),
            "coverage": {str(ep): list(items) for ep, items in sorted(self.coverage.items())},
            "case_index": case_index(self.tasks),
            "config_audit": config_audit.audit(
                self.tasks, [point.config for point in self.points],
                {f"EP{point.ep_size}/{point.suite}": case_dimension_records(
                    [case for case in catalog().values() if case.level == "L0"],
                    point.config["benchmark"], point.ep_size)
                 for point in self.points}),
        })
        return data


def _topology_record(config):
    topology = config.get("topology") or {}
    return {"source": topology.get("source", "unavailable"),
            "verified": bool(topology.get("verified", False)),
            "server_size": topology.get("server_size"),
            "servers": len(set(topology.get("server_ids") or ())),
            "supernodes": len(set(topology.get("supernode_ids") or ()))}


def _topology_summary(points, ep_size):
    """One topology record per EP size; contradictory maps are reported."""
    records = [_topology_record(point.config) for point in points if point.ep_size == ep_size]
    unique = {fingerprint(record): record for record in records}
    if len(unique) == 1:
        return next(iter(unique.values()))
    return {"source": "conflicting",
            "verified": all(record["verified"] for record in unique.values()),
            "variants": [record for record in unique.values()]}


def expand(plan, ep_sizes=None, suites=None, levels=None, cases=None, operators=None,
           aliases=None):
    """Expand a plan into a complete, integrity-checked task list."""
    selected_eps = list(ep_sizes or plan.ep_sizes)
    selected_suites = [normalize(item) for item in (suites or plan.suites)]
    requested_levels = list(levels) if levels else None
    effective_levels = requested_levels or list(plan.levels)
    cases = list(cases) if cases else None
    operators = operators if operators is not None else plan.operators
    points = plan_points(plan, selected_eps, selected_suites, effective_levels)
    store = {}
    for point in points:
        tasks = make_plan([point.config], operators=operators, levels=requested_levels,
                          cases=cases, suites=[point.suite],
                          aliases=aliases or plan.aliases)
        sources = [_relative(item) for item in point.sources]
        label = f"EP{point.ep_size}/{point.suite}"
        for task in tasks:
            task["config_source"] = list(sources)
            task["plan_point"] = label
            task["plan_points"] = [label]
        merge_tasks(store, tasks)
    ordered = sorted(store.values(),
                     key=lambda task: (task["ep_size"], task["level"], task["case_id"],
                                       task["backend_id"], task["task_id"]))
    expected = expected_cases(plan, selected_suites, effective_levels, cases)
    coverage = check_completeness(ordered, selected_eps, expected)
    return PlanRun(plan=plan, points=points, tasks=ordered, expected=expected,
                   coverage=coverage)


def matrix_metadata(tasks, ep_sizes=None, suites=None, levels=None):
    """Manifest metadata for a single-configuration run (no plan file)."""
    sizes = sorted(ep_sizes or {task["ep_size"] for task in tasks})
    suite_ids = list(dict.fromkeys(
        suite for task in tasks for suite in task.get("suite_ids", ())))
    topologies = {}
    for task in tasks:
        topologies.setdefault(task["ep_size"], _topology_record(task["config"]))
    return {
        "schema_version": PLAN_SCHEMA_VERSION,
        "name": "single-configuration",
        "mode": "catalog",
        "path": None,
        "ep_sizes": sizes,
        "levels": list(levels or sorted({task["level"] for task in tasks})),
        "suites": list(suites or suite_ids),
        "operators": sorted({task["backend_id"] for task in tasks}),
        "aliases": "dedupe",
        "execution": dict(DEFAULT_EXECUTION),
        "report": dict(DEFAULT_REPORT),
        "topology": {str(ep): record for ep, record in sorted(topologies.items())},
        "config_sources": {},
        "catalog": {
            case_id: {"level": case.level, "category": case.category,
                      "alias_of": case.alias_of, "canonical": case.alias_of is None}
            for case_id, case in sorted(catalog().items())
        },
        "case_aliases": alias_map(),
        "case_counts": case_counts(),
        "expected_cases": sorted({task["case_id"] for task in tasks}),
        "coverage": {str(ep): sorted({task["case_id"] for task in tasks if task["ep_size"] == ep})
                     for ep in sizes},
        "case_index": case_index(tasks),
    }
